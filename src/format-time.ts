/**
 * 时间戳格式化 —— 目前只剩「文件名安全的时间戳」一种。
 *
 * 为什么单独留一个模块：它进了**文件名与会话 id**（形如
 * `chat_YYYY_MM_DD_HH_mm_ss`；服务端生成会话 id 用的是同一套格式），是全仓唯一对时间做
 * 字符串化的地方，改动需要集中。
 *
 * 历史：本模块原有 6 个导出（相对时间 / 完整时间 / 紧凑时间 / 消息数 + 时间 / 文件大小），
 * 生产代码只用得上 `formatFileStamp` 一个 —— 其余几个的调用点早已不存在，
 * 它们的 `time.*` 词条在运行时不可达，故一并删除。将来要展示人类可读时间，
 * 从版本控制里取回即可，不必在这里「预留」。
 */

import dayjs from "dayjs";

/**
 * 文件名安全的时间戳：全下划线、纯数字，用作会话 id。
 * 例：2026_10_28_00_56_34
 *
 * **刻意不随界面语言变**：它进了文件名与会话 id，跟着语言变会让历史文件与新文件混排。
 */
export function formatFileStamp(isoString: string): string {
  return dayjs(isoString).format("YYYY_MM_DD_HH_mm_ss");
}
